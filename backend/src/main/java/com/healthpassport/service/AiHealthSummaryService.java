package com.healthpassport.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.healthpassport.dto.AiSummaryResponse;
import com.healthpassport.dto.AiSummaryStatusResponse;
import com.healthpassport.entity.AiHealthSummary;
import com.healthpassport.entity.MedicalRecord;
import com.healthpassport.entity.User;
import com.healthpassport.exception.ConflictException;
import com.healthpassport.exception.ResourceNotFoundException;
import com.healthpassport.repository.AiHealthSummaryRepository;
import com.healthpassport.repository.MedicalRecordRepository;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class AiHealthSummaryService {

    public static final String SUMMARY_DISCLAIMER =
        "AI Summarization Disclaimer: This summary is generated by a local AI model for informational purposes only. " +
        "It does not replace clinical advice, diagnosis, or treatment. AI summaries may contain errors or omissions; " +
        "always verify all measurements, medications, and instructions against your original medical record and consult a qualified healthcare provider.";

    public static final int MAX_INPUT_CHAR_LIMIT = 4000;

    private static final String SYSTEM_PROMPT =
        "You are a medical record summarization assistant for patients.\n" +
        "Your task is to analyze the provided patient medical report and organize the extracted details into clear, factual sections.\n" +
        "STRICT CLINICAL SAFETY RULES:\n" +
        "1. Never invent measurements, diagnoses, medications, reference ranges, or follow-up instructions.\n" +
        "2. Do not calculate disease probabilities, prescribe medication, recommend changing doses, or claim to replace a clinician.\n" +
        "3. Preserve all numerical values, units, and reference ranges exactly as written in the source.\n" +
        "4. If a category (e.g. medications, follow-up instructions, or measurements) is not present or mentioned in the source record, explicitly state 'Not specified in this record.'\n" +
        "5. Preserve any uncertainty or conflicting details mentioned by the provider.\n" +
        "6. Provide 2-3 neutral, helpful questions the patient can ask their doctor based on unclear or noteworthy details.\n\n" +
        "Format your answer EXACTLY using these 7 section headers (use Markdown bold headings or exact tags):\n" +
        "### Overview\n" +
        "### Key Findings\n" +
        "### Measurements and Results\n" +
        "### Medications\n" +
        "### Follow-up Instructions\n" +
        "### Questions for the Doctor\n" +
        "### Missing Information\n";

    private final OllamaClient ollamaClient;
    private final AiHealthSummaryRepository summaryRepository;
    private final MedicalRecordRepository recordRepository;
    private final UserService userService;
    private final ObjectMapper objectMapper;

    public AiHealthSummaryService(
        OllamaClient ollamaClient,
        AiHealthSummaryRepository summaryRepository,
        MedicalRecordRepository recordRepository,
        UserService userService,
        ObjectMapper objectMapper
    ) {
        this.ollamaClient = ollamaClient;
        this.summaryRepository = summaryRepository;
        this.recordRepository = recordRepository;
        this.userService = userService;
        this.objectMapper = objectMapper;
    }

    @Transactional(readOnly = true)
    public AiSummaryStatusResponse getStatus() {
        boolean available = ollamaClient.isAvailable();
        String model = ollamaClient.getProperties().getModel();
        String baseUrl = ollamaClient.getProperties().getBaseUrl();
        String message = available
            ? "Local Ollama service is connected and ready."
            : "Local Ollama service is currently unreachable at " + baseUrl + ". Start Ollama with 'ollama serve'.";

        return new AiSummaryStatusResponse(available, model, baseUrl, message);
    }

    @Transactional(readOnly = true)
    public Optional<AiSummaryResponse> getExistingSummary(String email, Long recordId) {
        User user = userService.findByEmail(email);
        MedicalRecord record = findOwnedRecord(user.getId(), recordId);

        return summaryRepository.findByRecordIdAndUserId(record.getId(), user.getId())
            .map(s -> toResponse(s, record, true));
    }

    @Transactional
    public AiSummaryResponse generateOrRefreshSummary(String email, Long recordId, boolean forceRefresh) {
        User user = userService.findByEmail(email);
        MedicalRecord record = findOwnedRecord(user.getId(), recordId);

        Optional<AiHealthSummary> existingOpt = summaryRepository.findByRecordIdAndUserId(record.getId(), user.getId());
        if (existingOpt.isPresent() && !forceRefresh) {
            return toResponse(existingOpt.get(), record, true);
        }

        // Validate source document has sufficient information
        String rawNotes = record.getNotes() != null ? record.getNotes().trim() : "";
        if (rawNotes.isBlank()) {
            throw new ConflictException(
                "This medical record does not contain any clinical notes or report text to summarize. Please update the record notes first."
            );
        }

        // Check input length boundary
        if (rawNotes.length() > MAX_INPUT_CHAR_LIMIT) {
            throw new ConflictException(
                "Clinical record content exceeds maximum supported length (" + MAX_INPUT_CHAR_LIMIT + " characters). Please split or condense the note to prevent loss of critical findings."
            );
        }

        // Build clean user prompt with structured context
        String userPrompt = buildUserPrompt(record, rawNotes);

        // Call Ollama local service
        String rawOutput = ollamaClient.generateSummary(SYSTEM_PROMPT, userPrompt);

        // Parse structured sections
        ParsedSections sections = parseOutputSections(rawOutput);

        AiHealthSummary summary = existingOpt.orElseGet(AiHealthSummary::new);
        summary.setUser(user);
        summary.setRecord(record);
        summary.setModelName(ollamaClient.getProperties().getModel());
        summary.setOverview(sections.overview);
        summary.setKeyFindings(sections.keyFindings);
        summary.setMeasurements(sections.measurements);
        summary.setMedications(sections.medications);
        summary.setFollowUpInstructions(sections.followUpInstructions);
        summary.setQuestionsForDoctor(sections.questionsForDoctor);
        summary.setMissingInformation(sections.missingInformation);
        summary.setDisclaimer(SUMMARY_DISCLAIMER);

        AiHealthSummary saved = summaryRepository.save(summary);
        return toResponse(saved, record, false);
    }

    private MedicalRecord findOwnedRecord(Long userId, Long recordId) {
        return recordRepository.findByIdAndUserId(recordId, userId)
            .orElseThrow(() -> new ResourceNotFoundException("Medical record not found or access denied"));
    }

    private String buildUserPrompt(MedicalRecord record, String notes) {
        StringBuilder sb = new StringBuilder();
        sb.append("RECORD TITLE: ").append(record.getTitle()).append("\n");
        sb.append("CATEGORY: ").append(record.getRecordType()).append("\n");
        if (record.getProviderName() != null && !record.getProviderName().isBlank()) {
            sb.append("PROVIDER / FACILITY: ").append(record.getProviderName()).append("\n");
        }
        sb.append("RECORD DATE: ").append(record.getRecordDate()).append("\n\n");
        sb.append("CLINICAL NOTES AND REPORT CONTENT:\n");
        sb.append(notes).append("\n\n");
        sb.append("Please summarize this record according to the required 7 sections.");
        return sb.toString();
    }

    public static class ParsedSections {
        public String overview = "Not specified in this record.";
        public String keyFindings = "Not specified in this record.";
        public String measurements = "Not specified in this record.";
        public String medications = "Not specified in this record.";
        public String followUpInstructions = "Not specified in this record.";
        public String questionsForDoctor = "Not specified in this record.";
        public String missingInformation = "Not specified in this record.";
    }

    ParsedSections parseOutputSections(String text) {
        ParsedSections res = new ParsedSections();
        if (text == null || text.isBlank()) {
            return res;
        }

        // Match common markdown headers or line headings
        Map<String, String> sectionMap = new HashMap<>();
        String[] sectionKeys = {
            "overview",
            "key findings",
            "measurements and results",
            "medications",
            "follow-up instructions",
            "questions for the doctor",
            "missing information"
        };

        // Regex pattern to extract sections
        Pattern pattern = Pattern.compile(
            "(?i)(?:###|\\*\\*|##)?\\s*(overview|key findings|measurements and results|measurements|medications|follow-up instructions|follow up instructions|questions for the doctor|questions|missing information)\\s*(?:\\*\\*)?:?\\s*([\\s\\S]*?)(?=(?:###|\\*\\*|##)?\\s*(?:overview|key findings|measurements and results|measurements|medications|follow-up instructions|follow up instructions|questions for the doctor|questions|missing information)\\s*(?:\\*\\*)?:?|$)"
        );

        Matcher matcher = pattern.matcher(text);
        while (matcher.find()) {
            String heading = matcher.group(1).trim().toLowerCase();
            String content = matcher.group(2).trim();

            if (heading.contains("overview")) sectionMap.put("overview", content);
            else if (heading.contains("findings")) sectionMap.put("key findings", content);
            else if (heading.contains("measurement")) sectionMap.put("measurements and results", content);
            else if (heading.contains("medication")) sectionMap.put("medications", content);
            else if (heading.contains("follow")) sectionMap.put("follow-up instructions", content);
            else if (heading.contains("question")) sectionMap.put("questions for the doctor", content);
            else if (heading.contains("missing")) sectionMap.put("missing information", content);
        }

        if (sectionMap.containsKey("overview") && !sectionMap.get("overview").isBlank()) {
            res.overview = sectionMap.get("overview");
        } else if (!text.isBlank() && sectionMap.isEmpty()) {
            // Fallback: put raw text into overview if headers weren't preserved
            res.overview = text.trim();
        }

        if (sectionMap.containsKey("key findings") && !sectionMap.get("key findings").isBlank()) {
            res.keyFindings = sectionMap.get("key findings");
        }
        if (sectionMap.containsKey("measurements and results") && !sectionMap.get("measurements and results").isBlank()) {
            res.measurements = sectionMap.get("measurements and results");
        }
        if (sectionMap.containsKey("medications") && !sectionMap.get("medications").isBlank()) {
            res.medications = sectionMap.get("medications");
        }
        if (sectionMap.containsKey("follow-up instructions") && !sectionMap.get("follow-up instructions").isBlank()) {
            res.followUpInstructions = sectionMap.get("follow-up instructions");
        }
        if (sectionMap.containsKey("questions for the doctor") && !sectionMap.get("questions for the doctor").isBlank()) {
            res.questionsForDoctor = sectionMap.get("questions for the doctor");
        }
        if (sectionMap.containsKey("missing information") && !sectionMap.get("missing information").isBlank()) {
            res.missingInformation = sectionMap.get("missing information");
        }

        return res;
    }

    private AiSummaryResponse toResponse(AiHealthSummary s, MedicalRecord record, boolean cached) {
        return new AiSummaryResponse(
            s.getId(),
            record.getId(),
            record.getTitle(),
            record.getRecordType(),
            record.getProviderName(),
            record.getRecordDate(),
            s.getModelName(),
            s.getOverview(),
            s.getKeyFindings(),
            s.getMeasurements(),
            s.getMedications(),
            s.getFollowUpInstructions(),
            s.getQuestionsForDoctor(),
            s.getMissingInformation(),
            s.getDisclaimer(),
            s.getUpdatedAt(),
            cached
        );
    }
}
